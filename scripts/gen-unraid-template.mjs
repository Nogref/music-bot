#!/usr/bin/env node
// Generates unraid/my-music-bot.xml from .env.example, so every variable and its
// comment shows up in Unraid's "Add Container" form.
//
// The file is named my-<container>.xml on purpose: that's the exact file Unraid saves
// your values into. A copy under any other name (e.g. music-bot.xml) sorts first,
// and Unraid's Edit/Update would keep loading that blank copy instead of your values.
//   node scripts/gen-unraid-template.mjs           write the template
//   node scripts/gen-unraid-template.mjs --check   fail if it's out of date (CI)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OWNER = process.env.GITHUB_OWNER ?? "Nogref";
const REPO = process.env.GITHUB_REPO ?? "music-bot";
const image = `ghcr.io/${OWNER.toLowerCase()}/${REPO}:latest`;
const raw = `https://raw.githubusercontent.com/${OWNER}/${REPO}/main`;

const REQUIRED = new Set(["DISCORD_TOKEN", "SUBSONIC_URL", "SUBSONIC_USER", "SUBSONIC_PASSWORD"]);
const SKIP = new Set(["DATA_DIR"]); // fixed to the /data path mapping below
// Shown by default; everything else sits behind Unraid's "Show more settings".
const ALWAYS = /^(DISCORD_TOKEN|OWNER_ID|ALLOWED_GUILD_IDS|SUBSONIC_URL|SUBSONIC_USER|SUBSONIC_PASSWORD|MUSIC_BITRATE|APEX_API_KEY)$/;
const MASK = /(TOKEN|KEY|SECRET|PASSWORD)$/;

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const lines = fs.readFileSync(path.join(root, ".env.example"), "utf8").split("\n");
const vars = [];
let comment = [];
let section = "";
for (const line of lines) {
  const t = line.trim();
  if (/^# ---/.test(t)) {
    section = t.replace(/^# -+\s*/, "").replace(/\s*-+$/, "");
    comment = [];
  } else if (t.startsWith("#") && !/^# =+/.test(t)) {
    comment.push(t.replace(/^#\s?/, ""));
  } else if (/^[A-Z0-9_]+=/.test(t)) {
    const [name, ...rest] = t.split("=");
    const value = rest.join("=");
    if (!SKIP.has(name)) vars.push({ name, value, description: [section, comment.join(" ")].filter(Boolean).join(" — ") });
    comment = [];
  } else if (!t) {
    comment = [];
  }
}

const configs = vars.map((v) => {
  const display = REQUIRED.has(v.name) || ALWAYS.test(v.name) ? "always" : "advanced";
  return `  <Config Name="${v.name}" Target="${v.name}" Default="${esc(v.value)}" Mode="" Description="${esc(v.description)}" Type="Variable" Display="${display}" Required="${REQUIRED.has(v.name)}" Mask="${MASK.test(v.name)}">${esc(v.value)}</Config>`;
});

const xml = `<?xml version="1.0"?>
<!-- Generated by scripts/gen-unraid-template.mjs from .env.example. Don't edit by hand. -->
<Container version="2">
  <Name>music-bot</Name>
  <Repository>${image}</Repository>
  <Registry>https://github.com/${OWNER}/${REPO}/pkgs/container/${REPO}</Registry>
  <Network>bridge</Network>
  <MyIP/>
  <Shell>sh</Shell>
  <Privileged>false</Privileged>
  <Support>https://github.com/${OWNER}/${REPO}/issues</Support>
  <Project>https://github.com/${OWNER}/${REPO}</Project>
  <Overview>Discord music bot that plays your own music library (Aurral's built-in Subsonic server, or Navidrome) in voice channels, in your server and your friends' servers. You approve each server from a Discord DM. Search-as-you-type /play, radio (random or songs like one you pick), lyrics, loop, seek, volume, queue controls and a live now-playing card. Optional Apex Legends stats: /apex link, stats, maps, Predator cutoff, a squad leaderboard and rank-up shout-outs. To reach Aurral by name (http://aurral:3001), put this container on the same custom Docker network; on plain bridge, use http://YOUR-UNRAID-IP:PORT.</Overview>
  <Category>MediaServer:Music Tools:</Category>
  <WebUI/>
  <TemplateURL>${raw}/unraid/my-music-bot.xml</TemplateURL>
  <Icon>${raw}/unraid/icon.png</Icon>
  <ExtraParams/>
  <PostArgs/>
  <CPUset/>
  <DonateText/>
  <DonateLink/>
  <Requires>A Discord bot token for a separate "music" application (see the README), and a login for the bot on Aurral (or another Subsonic server).</Requires>
  <Config Name="Appdata" Target="/data" Default="/mnt/user/appdata/music-bot" Mode="rw" Description="Small SQLite file: which servers are approved, each server's volume and now-playing board. Optional bot.env here fills in settings." Type="Path" Display="always" Required="true" Mask="false">/mnt/user/appdata/music-bot</Config>
${configs.join("\n")}
</Container>
`;

const out = path.join(root, "unraid", "my-music-bot.xml");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== xml) {
    console.error("unraid/my-music-bot.xml is out of date. Run: node scripts/gen-unraid-template.mjs");
    process.exit(1);
  }
  console.log(`Unraid template is up to date (${vars.length} variables).`);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, xml);
  console.log(`Wrote ${path.relative(root, out)} with ${vars.length} variables.`);
}
